#include "test_common.h"

int main(int argc, char **argv)
{
    REQUIRE(argc == 2);
    void *lib = dlopen(argv[1], RTLD_NOW | RTLD_LOCAL);
    if (!lib) { fprintf(stderr, "FAIL loading ICD: %s\n", dlerror()); return 1; }
    PFN_vkGetInstanceProcAddr gipa = (PFN_vkGetInstanceProcAddr)dlsym(lib, getenv("RADISH_USE_LOADER") ? "vkGetInstanceProcAddr" : "vk_icdGetInstanceProcAddr");
    REQUIRE(gipa);
    VkInstance instance = VK_NULL_HANDLE;
    INSTANCE_FN(CreateInstance);
    const VkApplicationInfo app = { .sType = VK_STRUCTURE_TYPE_APPLICATION_INFO, .pApplicationName = "radish-lifecycle", .apiVersion = VK_API_VERSION_1_0 };
    VkInstanceCreateInfo ici = { .sType = VK_STRUCTURE_TYPE_INSTANCE_CREATE_INFO, .pApplicationInfo = &app };
    const char *unknown = "VK_RADISH_not_supported";
    ici.enabledExtensionCount = 1;
    ici.ppEnabledExtensionNames = &unknown;
    REQUIRE(CreateInstance(&ici, NULL, &instance) == VK_ERROR_EXTENSION_NOT_PRESENT);
    const char *props_extension="VK_KHR_get_physical_device_properties2";
    ici.enabledExtensionCount = 1;
    ici.ppEnabledExtensionNames = &props_extension;
    SUCCESS(CreateInstance(&ici, NULL, &instance));
    INSTANCE_FN(DestroyInstance);
    INSTANCE_FN(EnumeratePhysicalDevices);
    INSTANCE_FN(GetPhysicalDeviceProperties);
    INSTANCE_FN(GetPhysicalDeviceProperties2KHR);
    INSTANCE_FN(GetPhysicalDeviceFeatures2KHR);
    INSTANCE_FN(GetPhysicalDeviceSparseImageFormatProperties2KHR);
    INSTANCE_FN(GetPhysicalDeviceFeatures);
    INSTANCE_FN(GetPhysicalDeviceFormatProperties);
    INSTANCE_FN(GetPhysicalDeviceImageFormatProperties);
    INSTANCE_FN(GetPhysicalDeviceMemoryProperties);
    INSTANCE_FN(GetPhysicalDeviceQueueFamilyProperties);
    INSTANCE_FN(CreateDevice);
    INSTANCE_FN(GetDeviceProcAddr);
    PFN_vkGetDeviceProcAddr gdpa = GetDeviceProcAddr;
    uint32_t count = 0;
    SUCCESS(EnumeratePhysicalDevices(instance, &count, NULL));
    if (getenv("RADISH_EXPECT_NO_DEVICE")) {
        REQUIRE(count == 0);
        DestroyInstance(instance, NULL);
        dlclose(lib);
        puts("PASS: unsupported host enumerates zero devices");
        return 0;
    }
    REQUIRE(count == 1);
    VkPhysicalDevice physical;
    SUCCESS(EnumeratePhysicalDevices(instance, &count, &physical));
    VkPhysicalDeviceProperties props;
    GetPhysicalDeviceProperties(physical, &props);
    REQUIRE(strstr(props.deviceName, "Radish") && strstr(props.deviceName, "506"));
    printf("device: %s api=%u.%u.%u\n", props.deviceName, VK_VERSION_MAJOR(props.apiVersion), VK_VERSION_MINOR(props.apiVersion), VK_VERSION_PATCH(props.apiVersion));
    VkPhysicalDeviceSubgroupProperties subgroup={.sType=VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_SUBGROUP_PROPERTIES};
    VkPhysicalDeviceProperties2 properties2={.sType=VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_PROPERTIES_2,.pNext=&subgroup};
    GetPhysicalDeviceProperties2KHR(physical,&properties2);
    REQUIRE(!strcmp(properties2.properties.deviceName,props.deviceName));
    REQUIRE(subgroup.subgroupSize>0 && !(subgroup.subgroupSize&(subgroup.subgroupSize-1)));
    REQUIRE(!subgroup.supportedOperations && !subgroup.supportedStages);
    VkPhysicalDeviceSparseImageFormatInfo2 sparse_info={.sType=VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_SPARSE_IMAGE_FORMAT_INFO_2,.format=VK_FORMAT_R32_SFLOAT,.type=VK_IMAGE_TYPE_3D,.samples=VK_SAMPLE_COUNT_1_BIT,.usage=VK_IMAGE_USAGE_STORAGE_BIT,.tiling=VK_IMAGE_TILING_OPTIMAL};
    uint32_t sparse_count=99;
    GetPhysicalDeviceSparseImageFormatProperties2KHR(physical,&sparse_info,&sparse_count,NULL);
    REQUIRE(sparse_count==0);
    fprintf(stderr,"checking unsupported image/format queries\n");
    VkFormatProperties format;
    memset(&format,0xAA,sizeof(format));
    GetPhysicalDeviceFormatProperties(physical,VK_FORMAT_R32_SFLOAT,&format);
    REQUIRE(!format.linearTilingFeatures && !format.optimalTilingFeatures && !format.bufferFeatures);
    VkImageFormatProperties image_format;
    REQUIRE(GetPhysicalDeviceImageFormatProperties(physical,VK_FORMAT_R32_SFLOAT,VK_IMAGE_TYPE_3D,VK_IMAGE_TILING_OPTIMAL,VK_IMAGE_USAGE_SAMPLED_BIT|VK_IMAGE_USAGE_STORAGE_BIT,0,&image_format)==VK_ERROR_FORMAT_NOT_SUPPORTED);
    VkPhysicalDeviceFeatures features;
    GetPhysicalDeviceFeatures(physical, &features);
    VkPhysicalDeviceFeatures2 features2={.sType=VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_FEATURES_2};
    GetPhysicalDeviceFeatures2KHR(physical,&features2);
    REQUIRE(!memcmp(&features,&features2.features,sizeof(features)));
    REQUIRE(!features.geometryShader && !features.tessellationShader && !features.shaderFloat64);
    VkQueueFamilyProperties queue;
    count = 1;
    GetPhysicalDeviceQueueFamilyProperties(physical, &count, &queue);
    REQUIRE(count == 1 && queue.queueCount == 1);
    REQUIRE((queue.queueFlags & VK_QUEUE_COMPUTE_BIT) && !(queue.queueFlags & VK_QUEUE_GRAPHICS_BIT));
    VkPhysicalDeviceMemoryProperties memprops;
    GetPhysicalDeviceMemoryProperties(physical, &memprops);
    REQUIRE(memprops.memoryTypeCount > 0 && (memprops.memoryTypes[0].propertyFlags & VK_MEMORY_PROPERTY_HOST_VISIBLE_BIT));
    float priority = 1;
    VkDeviceQueueCreateInfo qci = { .sType = VK_STRUCTURE_TYPE_DEVICE_QUEUE_CREATE_INFO, .queueFamilyIndex = 0, .queueCount = 1, .pQueuePriorities = &priority };
    VkDeviceCreateInfo dci = { .sType = VK_STRUCTURE_TYPE_DEVICE_CREATE_INFO, .queueCreateInfoCount = 1, .pQueueCreateInfos = &qci };
    VkDevice device;
    dci.enabledExtensionCount = 1;
    dci.ppEnabledExtensionNames = &unknown;
    REQUIRE(CreateDevice(physical, &dci, NULL, &device) == VK_ERROR_EXTENSION_NOT_PRESENT);
    dci.enabledExtensionCount = 0;
    VkPhysicalDeviceFeatures unsupported = { .shaderFloat64 = VK_TRUE };
    dci.pEnabledFeatures = &unsupported;
    REQUIRE(CreateDevice(physical, &dci, NULL, &device) == VK_ERROR_FEATURE_NOT_PRESENT);
    dci.pEnabledFeatures = NULL;
    for (unsigned iteration = 0; iteration < 24; iteration++) {
        SUCCESS(CreateDevice(physical, &dci, NULL, &device));
        DEVICE_FN(DestroyDevice);
        DEVICE_FN(GetDeviceQueue);
        DEVICE_FN(AllocateMemory);
        DEVICE_FN(FreeMemory);
        DEVICE_FN(MapMemory);
        DEVICE_FN(UnmapMemory);
        DEVICE_FN(FlushMappedMemoryRanges);
        DEVICE_FN(InvalidateMappedMemoryRanges);
        DEVICE_FN(CreateBuffer);
        DEVICE_FN(DestroyBuffer);
        DEVICE_FN(GetBufferMemoryRequirements);
        DEVICE_FN(BindBufferMemory);
        VkQueue handle = VK_NULL_HANDLE;
        GetDeviceQueue(device, 0, 0, &handle);
        REQUIRE(handle != VK_NULL_HANDLE);
        VkBuffer buffer;
        VkBufferCreateInfo bci = { .sType = VK_STRUCTURE_TYPE_BUFFER_CREATE_INFO, .size = 4099, .usage = VK_BUFFER_USAGE_STORAGE_BUFFER_BIT | VK_BUFFER_USAGE_TRANSFER_SRC_BIT | VK_BUFFER_USAGE_TRANSFER_DST_BIT, .sharingMode = VK_SHARING_MODE_EXCLUSIVE };
        SUCCESS(CreateBuffer(device, &bci, NULL, &buffer));
        VkMemoryRequirements req;
        GetBufferMemoryRequirements(device, buffer, &req);
        REQUIRE(req.size >= bci.size && req.alignment && (req.memoryTypeBits & 1));
        VkMemoryAllocateInfo mai = { .sType = VK_STRUCTURE_TYPE_MEMORY_ALLOCATE_INFO, .allocationSize = req.size + req.alignment, .memoryTypeIndex = 0 };
        VkDeviceMemory memory;
        SUCCESS(AllocateMemory(device, &mai, NULL, &memory));
        SUCCESS(BindBufferMemory(device, buffer, memory, req.alignment));
        void *mapped;
        SUCCESS(MapMemory(device, memory, 0, VK_WHOLE_SIZE, 0, &mapped));
        memset(mapped, iteration + 17, (size_t)mai.allocationSize);
        VkMappedMemoryRange range = { .sType = VK_STRUCTURE_TYPE_MAPPED_MEMORY_RANGE, .memory = memory, .offset = 0, .size = VK_WHOLE_SIZE };
        SUCCESS(FlushMappedMemoryRanges(device, 1, &range));
        UnmapMemory(device, memory);
        SUCCESS(MapMemory(device, memory, req.alignment, VK_WHOLE_SIZE, 0, &mapped));
        range.offset = req.alignment;
        SUCCESS(InvalidateMappedMemoryRanges(device, 1, &range));
        for (unsigned j = 0; j < bci.size; j++) REQUIRE(((uint8_t *)mapped)[j] == iteration + 17);
        UnmapMemory(device, memory);
        DestroyBuffer(device, buffer, NULL);
        FreeMemory(device, memory, NULL);
        DestroyDevice(device, NULL);
    }
    DestroyInstance(instance, NULL);
    dlclose(lib);
    puts("PASS: 24 device/buffer/BO cycles, mapping offsets, feature/extension rejection");
    return 0;
}
